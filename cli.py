def list_templates():
    print("\n📦 Available CrewAI Workflow Templates:")
    print("-------------------------------------------------------------")
    for key, info in TEMPLATES.items():
        print(f"  • {key:<22} : {info['name']}")
        print(f"    └─ {info['description']}")
    print("-------------------------------------------------------------\n")

def validate_workflow(workflow_data):
    issues = []
    nodes = workflow_data.get('nodes', [])
    connections = workflow_data.get('connections', [])

    agents = [n for n in nodes if n.get('type') == 'agent']
    tasks = [n for n in nodes if n.get('type') == 'task']
    crew = next((n for n in nodes if n.get('type') == 'crew'), None)

    if not agents:
        issues.append("ERROR: No Agent nodes defined. At least 1 agent is required.")
    if not tasks:
        issues.append("ERROR: No Task nodes defined. At least 1 task is required.")

    for t in tasks:
        task_id = t.get('id')
        has_agent = bool(t.get('agent_id'))
        has_conn = any(c.get('type') == 'agent-task' and (c.get('targetId') == task_id or c.get('sourceId') == task_id) for c in connections)
        if not has_agent and not has_conn:
            issues.append(f"WARNING: Task '{t.get('title') or t.get('name')}' has no assigned agent.")

    if crew and crew.get('process') == 'hierarchical' and not crew.get('manager_llm'):
        issues.append("ERROR: Hierarchical process selected but no manager_llm specified.")

    return issues

def sanitize(name):
    if not name:
        return 'item'
    clean = "".join(c if c.isalnum() or c == '_' else '_' for c in name.lower())
    return clean.strip('_') or 'item'

def generate_project(workflow_data, output_dir):
    out = Path(output_dir)
    config_dir = out / 'config'
    config_dir.mkdir(parents=True, exist_ok=True)

    nodes = workflow_data.get('nodes', [])
    connections = workflow_data.get('connections', [])

    agents = [n for n in nodes if n.get('type') == 'agent']
    tasks = [n for n in nodes if n.get('type') == 'task']
    tools = [n for n in nodes if n.get('type') == 'tool']
    crew = next((n for n in nodes if n.get('type') == 'crew'), {
        'name': 'AutonomousCrew',
        'process': 'sequential',
        'verbose': 2
    })

    # 1. agents.yaml
    agents_yaml = "# CrewAI Agent Configuration\n# Generated by Visual CrewAI CLI\n\n"
    for a in agents:
        key = sanitize(a.get('name') or a.get('role'))
        agents_yaml += f"{key}:\n"
        agents_yaml += f"  role: >\n    {a.get('role', '')}\n"
        agents_yaml += f"  goal: >\n    {a.get('goal', '')}\n"
        agents_yaml += f"  backstory: >\n    {a.get('backstory', '')}\n\n"
    (config_dir / 'agents.yaml').write_text(agents_yaml, encoding='utf-8')

    # 2. tasks.yaml
    tasks_yaml = "# CrewAI Task Configuration\n# Generated by Visual CrewAI CLI\n\n"
    for t in tasks:
        key = sanitize(t.get('name') or t.get('title'))
        # Find agent
        agent_key = 'default_agent'
        if t.get('agent_id'):
            matched = next((ag for ag in agents if ag.get('id') == t.get('agent_id')), None)
            if matched:
                agent_key = sanitize(matched.get('name') or matched.get('role'))
        tasks_yaml += f"{key}:\n"
        tasks_yaml += f"  description: >\n    {t.get('description', '')}\n"
        tasks_yaml += f"  expected_output: >\n    {t.get('expected_output', '')}\n"
        tasks_yaml += f"  agent: {agent_key}\n"
        if t.get('output_file'):
            tasks_yaml += f"  output_file: {t.get('output_file')}\n"
        tasks_yaml += "\n"
    (config_dir / 'tasks.yaml').write_text(tasks_yaml, encoding='utf-8')

