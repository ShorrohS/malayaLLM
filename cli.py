def main():
    parser = argparse.ArgumentParser(description="Visual CrewAI CLI Pipeline Orchestrator")
    subparsers = parser.add_subparsers(dest="command", help="Available subcommands")

    # Command: list
    subparsers.add_parser("list-templates", help="List all built-in CrewAI workflow templates")

    # Command: validate
    validate_parser = subparsers.add_parser("validate", help="Validate a workflow JSON file")
    validate_parser.add_argument("file", help="Path to workflow JSON file")

    # Command: generate
    gen_parser = subparsers.add_parser("generate", help="Generate CrewAI project files from workflow JSON")
    gen_parser.add_argument("file", help="Path to workflow JSON file")
    gen_parser.add_argument("--out-dir", default="generated_crew", help="Output directory path (default: ./generated_crew)")

    # Command: run-server
    subparsers.add_parser("serve", help="Launch the local visual workflow web interface")

    args = parser.parse_args()

    if args.command == "list-templates":
        list_templates()
    elif args.command == "validate":
        if not os.path.exists(args.file):
            print(f"❌ File not found: {args.file}")
            sys.exit(1)
        with open(args.file, 'r', encoding='utf-8') as f:
            data = json.load(f)
        issues = validate_workflow(data)
        if not issues:
            print("✅ Workflow validation PASSED! Clean and ready to run.")
        else:
            print(f"⚠️ Found {len(issues)} validation finding(s):")
            for issue in issues:
                print(f"  {issue}")
    elif args.command == "generate":
        if not os.path.exists(args.file):
            print(f"❌ File not found: {args.file}")
            sys.exit(1)
        with open(args.file, 'r', encoding='utf-8') as f:
            data = json.load(f)
        issues = validate_workflow(data)
        if any(i.startswith("ERROR") for i in issues):
            print("❌ Cannot generate due to fatal validation errors:")
            for i in issues:
                print(f"  {i}")
            sys.exit(1)
        generate_project(data, args.out_dir)
    elif args.command == "serve":
        from server import run_server
        run_server()
    else:
        parser.print_help()

if __name__ == "__main__":
    main()
